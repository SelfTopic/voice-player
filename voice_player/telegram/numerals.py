"""Число <-> русские слова числительных, для голосовых номеров треков Mr. Kitty.

Гарантированное резервное слово для трека — «трек <номер>» — работает для любого трека, даже
если автоматический перевод/транскрипция названия не прошли словарь модели (см. catalog.py).
"""

_ONES = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
_TEENS = [
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать",
]
_TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
_HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"]

# все слова, которые могут встретиться в number_to_words() -- нужно, чтобы распознать
# фразу, целиком состоящую из числительных (см. is_number_phrase)
NUMBER_WORDS = frozenset(["ноль", *_ONES[1:], *_TEENS, *_TENS[2:], *_HUNDREDS[1:]])


def number_to_words(n: int) -> str:
    """227 -> «двести двадцать семь». Только 0..999 — ровно то, что нужно для номеров треков."""
    if n == 0:
        return "ноль"
    if not 0 <= n < 1000:
        raise ValueError(f"ожидалось число 0..999, получено {n}")
    parts = []
    hundreds, rem = divmod(n, 100)
    if hundreds:
        parts.append(_HUNDREDS[hundreds])
    if 10 <= rem < 20:
        parts.append(_TEENS[rem - 10])
    else:
        tens, ones = divmod(rem, 10)
        if tens:
            parts.append(_TENS[tens])
        if ones:
            parts.append(_ONES[ones])
    return " ".join(parts)


def is_number_phrase(phrase: str) -> bool:
    """Состоит ли фраза целиком из слов-числительных.

    Нужно, чтобы НЕ ловить такие фразы по частичному распознаванию: «сто» — законченная
    команда сама по себе и одновременно префикс «сто сорок» — быстрый путь стреляет по «сто»
    раньше, чем модель договорит «сорок» (см. SLOW_ONLY в commands.py и command_at_end).
    """
    words = phrase.split()
    return bool(words) and all(word in NUMBER_WORDS for word in words)
